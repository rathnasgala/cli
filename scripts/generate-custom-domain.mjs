import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = join(root, 'contracts', 'custom-domain.json');
const target = join(root, 'src', 'domain.js');
const contract = JSON.parse(await readFile(contractPath, 'utf8'));

const expected = `// Generated by scripts/generate-custom-domain.mjs. Do not edit.\n`
  + `const HOST = new RegExp(${JSON.stringify(contract.hostnamePattern)});\n`
  + `const MAXIMUM_HOSTNAME_LENGTH = ${contract.maximumHostnameLength};\n`
  + `const FORBIDDEN_PREFIXES = ${JSON.stringify(contract.forbiddenPrefixes)};\n`
  + `const FORBIDDEN_SUFFIXES = ${JSON.stringify(contract.forbiddenSuffixes)};\n`
  + `const MESSAGE = ${JSON.stringify(contract.messages, null, 2)};\n\n`
  + `export function customDomain(value) {\n`
  + `  const source = typeof value === 'string' ? value.trim().toLowerCase().replace(/\\.$/, '') : '';\n`
  + `  if (!source) return { error: MESSAGE.empty };\n`
  + `  try {\n`
  + `    const parsed = new URL(\`https://\${source}\`);\n`
  + `    if (parsed.username || parsed.password || parsed.port || parsed.pathname !== '/'\n`
  + `        || parsed.search || parsed.hash || parsed.hostname !== source) {\n`
  + `      return { error: MESSAGE.components };\n`
  + `    }\n`
  + `    if (source.length > MAXIMUM_HOSTNAME_LENGTH\n`
  + `        || FORBIDDEN_PREFIXES.some((prefix) => source.startsWith(prefix))\n`
  + `        || FORBIDDEN_SUFFIXES.some((suffix) => source.endsWith(suffix))) {\n`
  + `      return { error: MESSAGE.policy };\n`
  + `    }\n`
  + `    if (!HOST.test(source)) return { error: MESSAGE.labels };\n`
  + `    return { host: source };\n`
  + `  } catch {\n`
  + `    return { error: MESSAGE.invalid };\n`
  + `  }\n`
  + `}\n`;

if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== expected) {
    throw new Error(`${target} is stale; run node scripts/generate-custom-domain.mjs`);
  }
} else {
  await writeFile(target, expected);
}
